def main():
    seen = {}
    kept = []
    dups = []
    for name, cat, rows in shapes():
        key = tuple(rows)
        if key in seen:
            dups.append(f"{name} (igual a {seen[key]})")
            continue
        seen[key] = name
        kept.append((name, cat, rows))

    lines = []
    lines.append("package com.pixelados.data.model")
    lines.append("")
    lines.append("import androidx.compose.ui.graphics.Color")
    lines.append("")
    lines.append("/**")
    lines.append(" * Catálogo de símbolos del editor (formas pixel-art).")
    lines.append(" *")
    lines.append(" * Generado a partir de figuras geométricas simples para que se lean bien")
    lines.append(" * a tamaño de cuadrícula. Se guarda la máscara (relleno/no relleno) y el")
    lines.append(" * color lo pone el color activo al estampar.")
    lines.append(" *")
    lines.append(" * Total: %d símbolos, sin repetidos." % len(kept))
    lines.append(" */")
    lines.append("object StampCatalog {")
    lines.append("")
    cats = []
    for _, cat, _ in kept:
        if cat not in cats:
            cats.append(cat)
    lines.append("    val categories: List<String> = listOf(%s)" % ", ".join('"%s"' % c for c in cats))
    lines.append("")
    lines.append("    private const val ON = -0x1000000 // 0xFF000000: celda rellena")
    lines.append("    private const val OFF = 0 // transparente: hueco")
    lines.append("")
    lines.append("    private fun mask(vararg rows: String): List<List<Int>> =")
    lines.append("        rows.map { row -> row.map { if (it == '1') ON else OFF } }")
    lines.append("")
    lines.append("    val all: List<Stamp> = listOf(")
    for name, cat, rows in kept:
        lines.append('        Stamp(')
        lines.append('            name = "%s",' % name)
        lines.append('            category = "%s",' % cat)
        lines.append('            pattern = mask(')
        for r in rows:
            lines.append('                "%s",' % r)
        lines.append('            )')
        lines.append('        ),')
    lines.append("    )")
    lines.append("}")
    out = "\n".join(lines) + "\n"
    path = r"C:\GitHub\pixelados\app\src\main\java\com\pixelados\data\model\StampCatalog.kt"
    with open(path, "w", encoding="utf-8") as f:
        f.write(out)
    print("simbolos:", len(kept), "descartados por repetidos:", len(dups))
    for d in dups:
        print("  -", d)


if __name__ == "__main__":
    main()
