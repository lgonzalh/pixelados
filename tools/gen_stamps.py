"""Genera el catalogo de simbolos de Pixelados como mascaras pixel-art.

Cada figura se dibuja con primitivas sobre un lienzo N x N y se reduce a una
cuadricula de pixeles (supersampling + umbral). Se deduplican por su huella.
Salida: Kotlin con las matrices listas para el editor.
"""
import math
from PIL import Image, ImageDraw

S = 8  # supersampling
ON = "1"
OFF = "0"


def canvas(n):
    c = Image.new("L", (n * S, n * S), 0)
    return c, ImageDraw.Draw(c)


def E(d, x0, y0, x1, y1, v=255):
    d.ellipse([x0 * S, y0 * S, x1 * S, y1 * S], fill=v)


def R(d, x0, y0, x1, y1, v=255):
    d.rectangle([x0 * S, y0 * S, x1 * S, y1 * S], fill=v)


def P(d, pts, v=255):
    d.polygon([(x * S, y * S) for x, y in pts], fill=v)


def L(d, pts, w=1.0, v=255):
    d.line([(x * S, y * S) for x, y in pts], fill=v, width=int(w * S), joint="curve")


def ring(d, x0, y0, x1, y1, w=1.0, v=255):
    d.ellipse([x0 * S, y0 * S, x1 * S, y1 * S], outline=v, width=int(w * S))


def regular(n, sides, cx=None, cy=None, r=None, rot=0.0):
    cx = (n - 1) / 2 if cx is None else cx
    cy = (n - 1) / 2 if cy is None else cy
    r = n / 2 - 0.5 if r is None else r
    return [
        (cx + r * math.cos(rot + 2 * math.pi * i / sides),
         cy + r * math.sin(rot + 2 * math.pi * i / sides))
        for i in range(sides)
    ]


def star_pts(n, points=5, inner=0.45, cx=None, cy=None, r=None, rot=-math.pi / 2):
    cx = (n - 1) / 2 if cx is None else cx
    cy = (n - 1) / 2 if cy is None else cy
    r = n / 2 - 0.5 if r is None else r
    out = []
    for i in range(points * 2):
        rr = r if i % 2 == 0 else r * inner
        a = rot + math.pi * i / points
        out.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return out


def to_mask(img, n, threshold=0.5):
    small = img.resize((n, n), Image.BOX)
    px = small.load()
    rows = []
    for y in range(n):
        rows.append("".join(ON if px[x, y] / 255 >= threshold else OFF for x in range(n)))
    return rows


